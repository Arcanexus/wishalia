/** Decodes the HTML entities of a text or an attribute; an unknown one stays as it is. */
export function decodeEntities(text: string): string {
  return text.replace(/&(#x[\da-f]+|#\d+|[a-z][a-z\d]*);/gi, (whole, name: string) => {
    if (name[0] === "#") {
      const code = name[1]?.toLowerCase() === "x" ? parseInt(name.slice(2), 16) : parseInt(name.slice(1), 10);
      return Number.isFinite(code) && code > 0 && code <= 0x10ffff ? String.fromCodePoint(code) : whole;
    }
    // Case matters (« &Agrave; » is not « &agrave; »), except for the XML ones old pages write in capitals
    const code = NAMED[name] ?? XML[name.toLowerCase()];
    return code === undefined ? whole : String.fromCodePoint(code);
  });
}
